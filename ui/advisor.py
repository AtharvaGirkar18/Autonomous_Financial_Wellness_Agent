from __future__ import annotations

import streamlit as st

from tools.llm import llm_status


def render_advisor(state: dict) -> None:
    status = llm_status()
    ai_on = status["enabled"]

    # Status badge
    if ai_on:
        provider_name = "Gemini" if status["provider"] == "google" else ("Grok" if status["provider"] == "grok" else status["provider"].title())
        st.success(
            f"✨ AI available ({provider_name} — {status['model']}). "
            "Recommendations are grounded in profile data; direct purchase affordability checks use deterministic calculations."
        )
    else:
        st.info(
            "🔢 Deterministic mode — no API key configured. "
            "All recommendations below are calculated directly from your financial data (no AI). "
            "Add your API key to the .env file (GOOGLE_API_KEY or XAI_API_KEY) to enable AI-powered responses."
        )

    reviewer = state.get("reviewer", {})
    if reviewer:
        rstat = reviewer.get("status", "UNKNOWN")
        color = "🟢" if rstat == "PASSED" else "🔴"
        st.caption(
            f"{color} Reviewer: **{rstat}** · "
            f"Grounded recommendations: {reviewer.get('grounded_recommendations', 0)}"
        )

    recs = state.get("recommendations", [])
    if not recs:
        st.info("Run an analysis or ask a question below to see recommendations.")
        return

    for i, rec in enumerate(recs):
        evidence = rec.get("evidence", {})
        is_guardrail = evidence.get("guardrail") is not None or evidence.get("llm_role") == "guardrail_response"
        is_llm = evidence.get("llm_role") == "language_only"
        if is_guardrail:
            label = "🛡️ Input Guardrail: Off-Topic Filter"
        elif is_llm:
            label = "✨ AI Summary"
        else:
            label = f"📊 Recommendation {i + (0 if is_llm else 1)}"

        with st.container():
            st.markdown(f"**{label}**")
            if is_guardrail:
                st.warning(rec["text"])
            else:
                st.markdown(rec["text"])
            with st.expander("Evidence & source data", expanded=False):
                if evidence.get("guardrail"):
                    st.caption("This query was intercepted by the deterministic Domain Scope Guardrail before reaching the LLM.")
                elif evidence.get("llm_role"):
                    st.caption("The text above was generated by the LLM grounded on deterministic financial evidence.")
                st.json(evidence)
            st.divider()
